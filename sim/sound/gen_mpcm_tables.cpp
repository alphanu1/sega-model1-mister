// Prints m2_multipcm's envelope ROMs from multipcm_ref.h, the transcription of
// MAME's gew.cpp, so the RTL's constants come from the same float arithmetic
// the reference uses rather than from a second derivation.
//   g++ -O2 -I sim/sound sim/sound/gen_mpcm_tables.cpp -o build/gen_mpcm_tables
#include "multipcm_ref.h"
#include <cstdio>
int main() {
  MultiPcmRef r(10000000.0f);
  std::printf("// ---- generated by sim/sound/gen_mpcm_tables.cpp: EG step ROM {decay, idx}\n");
  for (int t = 0; t < 2; t++)
    for (int i = 0; i < 64; i++)
      std::printf("      7'd%d: q <= 27'd%u;\n", t * 64 + i, t ? r.decay_step[i] : r.attack_step[i]);
  std::printf("// ---- lin2exp\n");
  for (int i = 0; i < 1024; i++) {
    if (i % 8 == 0) std::printf("     ");
    std::printf(" 10'd%d: q <= 13'd%d;", i, r.lin2exp[i]);
    if (i % 8 == 7) std::printf("\n");
  }
  return 0;
}
