# Generates rtl/sound/dsb_tables.svh: the constant tables of the DSB's MPEG-1
# Layer II decoder. None of this is ROM data -- it is ISO/IEC 11172-3's
# synthesis window (read out of MAME's mpeg_audio.cpp, where it is printed as
# k/65536 exactly) and three derived constants, rounded EXACTLY as
# tools/dsb/dsb_fixmodel.h rounds them (llround: half away from zero), so the
# RTL and the C model hold the same integers.
#
#   python3 tools/dsb/gen_tables.py <mame>/src/devices/sound/mpeg_audio.cpp
import math, re, sys

def llround(x):
    return int(math.copysign(math.floor(abs(x) + 0.5), x))

src = open(sys.argv[1]).read()
m = re.search(r's_synthesis_filter\[512\] = \{(.*?)\};', src, re.S)
win = [llround(float(v) * 65536) for v in re.findall(r'[-+]?\d+\.\d+', m.group(1))]
assert len(win) == 512 and max(abs(w) for w in win) < 2**17

cos = [llround(math.cos(k * math.pi / 64) * 2**17) for k in range(64)]
# cos(k*pi/64) for k >= 64 is exactly -cos((k-64)*pi/64) at this rounding.
for k in range(64):
    assert llround(math.cos((k + 64) * math.pi / 64) * 2**17) == -cos[k]
scf = [llround(2.0 ** (1.0 - s / 3.0) * 2**22) for s in range(63)] + [0]
r = [0, 1-1.0/4, 1-3.0/8, 1-1.0/8, 1-7.0/16] + [1 - 1.0 / 2**n for n in range(4, 17)]
cq = [0] + [llround((1 / r[k]) * 2**16) for k in range(1, 18)]

out = []
out.append('// Generated by tools/dsb/gen_tables.py -- do not edit.')
out.append('// The window is ISO/IEC 11172-3\'s, as printed in MAME\'s src/devices/sound/')
out.append('// mpeg_audio.cpp (BSD-3-Clause, copyright Olivier Galibert); the rest is derived.')
out.append('// win: ISO 11172-3 synthesis window x 65536 (exact). misc: [0..63] cos(k*pi/64) x 2^17,')
out.append('// [64..127] 2^(1-s/3) x 2^22 (s=63 -> 0), [128..145] requantisation C x 2^16.')
out.append('initial begin')
for i, w in enumerate(win):
    out.append(f'  win[{i}] = {w & 0x3ffff};')
for i, v in enumerate(cos):
    out.append(f'  misc[{i}] = 32\'d{v & 0xffffffff};')
for i, v in enumerate(scf):
    out.append(f'  misc[{64+i}] = 32\'d{v};')
for i, v in enumerate(cq):
    out.append(f'  misc[{128+i}] = 32\'d{v};')
out.append('end')
open(sys.argv[2] if len(sys.argv) > 2 else 'rtl/sound/dsb_tables.svh', 'w').write('\n'.join(out) + '\n')
print('ok', len(win), len(cos), len(scf), len(cq))
